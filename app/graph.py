from app.observability import trace
from app.aws import embed, answer
from app.vector import search
from app.config import get_settings
from app.guardrails import check_input, check_output

from typing import TypedDict, Any
from langgraph.graph import START, END, StateGraph


#node -> edge -> node and pass state between them

class State(TypedDict):
    question:str
    principle:Any #info about the user like id, tenant, role etc
    passages:list #relevant document retrieved from the vector database
    answer:str  #final response generated by model
    sources:list #source llm uses
    status:str #current audit event
    history:list #convo history, previous turns, etc


@trace("guard")
def guard(s): #check input question
    return {'question' : check_input(s['question'])}

@trace("retrieve")
def retrieve(s): #retrieve the documents form vector db
    p = s['principle']
    prior_questions=[m['content'] for m in s.get('history', []) if m['role'] == 'user']
    query=(prior_questions[-1]+'\nFollow up: '+s['question']) if prior_questions else s['question']
    hits=search(p.tenant, embed(query), p.groups, p.subject)
    hits=[h for h in hits if h['score']>=get_settings().min_relevance]
    sources=[
        {
            'index': i+1,
            'document_id' : h['metadata'].get('document_id', ''),
            'title' : h['metadata'].get('title', ''),
            'page' : h['metadata'].get('page', 1),
            'excerpt' : h['metadata'].get('text', '')[:320]
        } for i,h in enumerate(hits)
    ]
    return {
        'passages':hits,
        'sources': sources
    }

#now we have the context

def route(s): #router decided whether to use the context or not 
    return 'generate' if s['passages'] else 'no_evidence'

#no evidence
@trace("no_evidence")
def no_evidence(s):
    return{'answer': 'I count not find any supporting evidence in the knowledge base you are authorized to access.' ,
           'status': 'no_evidence'}

@trace("generate")
def generate(s):
    evidence='\n\n'.join(f'[{i+1}] {h["metadata"].get("title", "Document")}, page {h["metadata"].get("page",1)}: {h["metadata"].get("text", "")}' for i,h in enumerate(s['passages']))
    return {'answer': answer(s['question'],evidence,s.get('history', [])), 'status':'answered'}

@trace("validate")
@trace("validate")
def validate(s):
    try:
        return {'answer': check_output(s['answer'])}
    except Exception:
        return {'answer': "I can't share that information.", 'status': 'blocked', 'sources': []}

def make_graph():
    g = StateGraph(State)
    for name,func in [('guard',guard),('retrieve',retrieve),('no_evidence',no_evidence),('generate',generate),('validate',validate)]:
        g.add_node(name, func)
    g.add_edge(START, 'guard')
    g.add_edge('guard', 'retrieve')
    g.add_conditional_edges('retrieve', route, {'generate': 'generate', 'no_evidence': 'no_evidence'})
    g.add_edge('generate', 'validate')
    g.add_edge('validate', END)
    g.add_edge('no_evidence', END)
    return g.compile()

graph = make_graph()


@trace("chat")
def chat(p, question, history=None):
    r=graph.invoke({'principle': p, 'question' : question, 'history': history or []})
    return {'answer':r['answer'], 
            'sources':r.get('sources', []), 
            'status':r.get('status' , 'answered')}




